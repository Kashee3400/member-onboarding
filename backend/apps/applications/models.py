from django.conf import settings
from django.db import models
from django.db.models import Q

from apps.hierarchy.models import Mpp
from apps.organizations.models import OrganizationOwnedModel


class Status(models.TextChoices):
    DRAFT = "draft", "Draft"
    PENDING_AM = "pending_am", "Pending Area Manager"
    PENDING_CS = "pending_cs", "Pending CS & Legal"
    PENDING_FINANCE = "pending_finance", "Pending Finance"
    REJECTED = "rejected", "Rejected"
    APPROVED = "approved", "Approved"
    DISCARDED = "discarded", "Discarded"


class Decision(models.TextChoices):
    APPROVED = "approved", "Approved"
    REJECTED = "rejected", "Rejected"


class Application(OrganizationOwnedModel):
    """
    A membership form. It belongs to the MPP, not to whoever filled it, so a
    facilitator's departure moves access without moving any data. The people who
    worked on it are kept here, with their names copied in case an account goes.
    """

    client_id = models.CharField(
        max_length=100, help_text="Generated by the device, so a retried create is not doubled."
    )
    mpp = models.ForeignKey(Mpp, on_delete=models.PROTECT, related_name="applications")
    status = models.CharField(
        max_length=20, choices=Status.choices, default=Status.DRAFT, db_index=True
    )
    form_number = models.CharField(max_length=20, blank=True)
    form_version = models.PositiveSmallIntegerField(default=1)
    version = models.PositiveIntegerField(default=1, help_text="Rejects overlapping edits.")
    revision = models.PositiveIntegerField(default=0, help_text="Number of submissions so far.")
    data = models.JSONField(default=dict, blank=True)

    aadhaar_encrypted = models.TextField(blank=True)
    aadhaar_index = models.CharField(max_length=64, blank=True)
    aadhaar_last4 = models.CharField(max_length=4, blank=True)
    account_encrypted = models.TextField(blank=True)
    account_index = models.CharField(max_length=64, blank=True)
    account_last4 = models.CharField(max_length=4, blank=True)

    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="+"
    )
    created_by_name = models.CharField(max_length=200)
    last_edited_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="+"
    )
    last_edited_by_name = models.CharField(max_length=200)
    submitted_at = models.DateTimeField(null=True, blank=True)

    rejection_reason = models.TextField(blank=True)
    rejected_fields = models.JSONField(default=list, blank=True)
    payment = models.JSONField(default=dict, blank=True)
    # Set by a confirmed OTP, never by the form. Cleared when the number or address changes.
    mobile_verified_at = models.DateTimeField(null=True, blank=True)
    email_verified_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        db_table = "application"
        indexes = [
            models.Index(fields=["mpp", "status"], name="application_mpp_status_idx"),
        ]
        constraints = [
            models.UniqueConstraint(
                fields=["organization", "client_id"], name="unique_application_client_id"
            ),
            models.UniqueConstraint(
                fields=["organization", "form_number"],
                condition=~Q(form_number=""),
                name="unique_application_form_number",
            ),
            models.UniqueConstraint(
                fields=["organization", "aadhaar_index"],
                condition=~Q(aadhaar_index="") & ~Q(status="discarded"),
                name="unique_live_application_per_aadhaar",
            ),
        ]

    def __str__(self):
        return self.form_number or str(self.id)


class ApplicationRevision(OrganizationOwnedModel):
    """An immutable copy of what was submitted, so approvers can compare resubmissions."""

    application = models.ForeignKey(Application, on_delete=models.CASCADE, related_name="revisions")
    number = models.PositiveIntegerField()
    data = models.JSONField()
    aadhaar_last4 = models.CharField(max_length=4)
    account_last4 = models.CharField(max_length=4)
    submitted_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="+"
    )
    submitted_by_name = models.CharField(max_length=200)
    signature = models.ForeignKey(
        "documents.StaffSignature", on_delete=models.PROTECT, related_name="+"
    )
    submitted_at = models.DateTimeField()

    class Meta:
        db_table = "application_revision"
        ordering = ["-number"]
        constraints = [
            models.UniqueConstraint(
                fields=["application", "number"], name="unique_revision_number"
            ),
        ]

    def __str__(self):
        return f"{self.application_id} r{self.number}"


class ApplicationDecision(OrganizationOwnedModel):
    application = models.ForeignKey(Application, on_delete=models.CASCADE, related_name="decisions")
    revision = models.PositiveIntegerField()
    stage = models.CharField(max_length=20, choices=Status.choices)
    decision = models.CharField(max_length=10, choices=Decision.choices)
    reason = models.TextField(blank=True)
    # Kept here too, because the form forgets them once it is sent again.
    rejected_fields = models.JSONField(default=list, blank=True)
    decided_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="+"
    )
    decided_by_name = models.CharField(max_length=200)
    signature = models.ForeignKey(
        "documents.StaffSignature", on_delete=models.PROTECT, related_name="+"
    )
    # The head whose signature the printed form carries, who may not be who decided.
    signed_by_name = models.CharField(max_length=200, blank=True)
    decided_at = models.DateTimeField()

    class Meta:
        db_table = "application_decision"
        ordering = ["decided_at"]
        constraints = [
            models.UniqueConstraint(
                fields=["application", "revision", "stage"], name="unique_decision_per_stage"
            ),
        ]

    def __str__(self):
        return f"{self.stage}: {self.decision}"


